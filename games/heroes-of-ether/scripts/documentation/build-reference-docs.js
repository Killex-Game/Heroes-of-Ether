const cell = (value) =>
  String(value ?? "—")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ");
function table(headers, rows) {
  return (
    [headers, headers.map(() => "---"), ...rows]
      .map((row) => "| " + row.map(cell).join(" | ") + " |")
      .join("\n") + "\n"
  );
}
function write(file, text) {
  const target = path.join(root, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, text.trim() + "\n");
}
function rule(name, title, source, content) {
  write(
    "docs/rules/" + name + ".md",
    "# " +
      title +
      "\n\nСправочник сформирован из текущего кода командой `npm run docs:refresh`.\n\n" +
      "Источник: [модуль правил](../../" +
      source +
      ").\n\n" +
      content,
  );
}
function files(directory) {
  return fs.readdirSync(path.join(root, directory), { withFileTypes: true }).flatMap((item) => {
    if (["assets", "artifacts"].includes(item.name) || item.name.startsWith(".tmp-")) return [];
    const relative = directory + "/" + item.name;
    return item.isDirectory() ? files(relative) : [relative];
  });
}

