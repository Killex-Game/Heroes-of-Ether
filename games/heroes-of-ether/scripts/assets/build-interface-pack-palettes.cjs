/* Generate additional palette scopes without rewriting the existing stylesheets. */
"use strict";
const fs = require("node:fs"),
  path = require("node:path");
const theme = require("../../public/shared/interface-theme");
const catalog = require("../../public/shared/league-appearance");
const root = path.resolve(__dirname, "../.."),
  publicRoot = path.join(root, "public");
const input = fs.readFileSync(path.join(publicRoot, "styles/theme/interface-themes.css"), "utf8");
const defaults = input.match(/\[data-ui-theme="default"\] \{([\s\S]*?)\n\}/)[1];
let output = "/* Generated by scripts/assets/build-interface-pack-palettes.cjs. */\n";
for (const { id } of catalog.interfaceThemes) {
  const block = defaults
    .replace(
      /(--ui-c-([a-f\d]+):\s*)#[a-f\d]+/gi,
      (_, before, hex) => before + theme.color("#" + hex, id),
    )
    .replace(/url\("\.\.\/\.\.\/(assets\/ui\/svg\/([^"]+))"\)/g, (_, source, short) => {
      const target = `assets/interface-packs/${id}/ui/${short}`;
      const svg = fs
        .readFileSync(path.join(publicRoot, source), "utf8")
        .replace(
          /((?:fill|stroke|stop-color|flood-color)=["'])(#[a-f\d]{3,8})(["'])/gi,
          (_, before, hex, after) => before + theme.color(hex, id) + after,
        );
      fs.mkdirSync(path.dirname(path.join(publicRoot, target)), { recursive: true });
      fs.writeFileSync(path.join(publicRoot, target), svg);
      return `url("../../${target}")`;
    });
  output += `[data-ui-theme="${id}"] {${block}\n}\n`;
}
fs.writeFileSync(path.join(publicRoot, "styles/theme/interface-pack-palettes.css"), output);
console.log("Built three interface palette scopes");
