/* The approved base palette, separate from purchased/event and clan themes.
   Generate materials once at build time; no per-frame recolouring. */
"use strict";
const fs = require("node:fs"), path = require("node:path");
const root = path.resolve(__dirname, "../../public");
const source = fs.readFileSync(path.join(root, "styles/theme/interface-themes.css"), "utf8");
const original = source.match(/\[data-ui-theme="default"\] \{([\s\S]*?)\n\}/)[1];
const channels = hex => {
  let s = hex.slice(1); if (s.length < 5) s = [...s].map(c => c + c).join("");
  return { rgb: [0, 2, 4].map(i => parseInt(s.slice(i, i + 2), 16)), alpha: s.slice(6) };
};
const mix = (a, b, t) => a.map((v, i) => Math.round(v + (b[i] - v) * t));
function material(hex) {
  const { rgb, alpha } = channels(hex), max = Math.max(...rgb), min = Math.min(...rgb);
  if (max === min) return hex; // Keep white highlights and neutral masks.
  const light = (max + min) / 510, [r, g, b] = rgb;
  let result;
  if (light > .76) result = mix([238, 228, 205], [255, 247, 230], (light - .76) / .24);
  else if (r > b * 1.12 && g > b * 1.06 && r >= g) result = mix([137, 101, 46], [238, 203, 120], Math.min(1, light / .8));
  else if (light <= .38) result = mix([12, 25, 35], [41, 62, 80], light / .38);
  else result = mix([49, 95, 124], [184, 207, 218], Math.min(1, (light - .38) / .38));
  return "#" + result.map(n => n.toString(16).padStart(2, "0")).join("") + alpha;
}
let count = 0;
const block = original.replace(/(--ui-c-[a-f\d]+:\s*)(#[a-f\d]+)/gi, (_, lead, hex) => lead + material(hex))
  .replace(/url\("\.\.\/\.\.\/(assets\/ui\/svg\/([^\"]+))"\)/g, (_, source, short) => {
    const target = `assets/ui/themes/azure-base/${short}`;
    let svg = fs.readFileSync(path.join(root, source), "utf8");
    svg = svg.replace(/((?:fill|stroke|stop-color|flood-color)=["'])(#[a-f\d]{3,8})(["'])/gi,
      (_, before, hex, after) => before + material(hex) + after);
    fs.mkdirSync(path.dirname(path.join(root, target)), { recursive: true });
    fs.writeFileSync(path.join(root, target), svg); count++;
    return `url("../../${target}")`;
  });
fs.writeFileSync(path.join(root, "styles/theme/base-palette-materials.css"),
  '/* Generated by scripts/assets/build-base-palette.cjs. */\n[data-ui-theme="default"] {' + block + '\n}\n');
console.log(`Built azure/champagne materials: ${count} SVGs`);
