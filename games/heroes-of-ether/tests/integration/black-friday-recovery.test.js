"use strict";
const test = require("node:test"), assert = require("node:assert/strict");
const fs = require("node:fs"), os = require("node:os"), path = require("node:path");
const { spawnSync } = require("node:child_process");
const { randomUUID } = require("node:crypto");
const { ProfileStore } = require("../../src/server/profiles/profile-store");
const { EventManager } = require("../../src/server/events/event-manager");
const { recover } = require("../../src/server/profiles/profile-journal");
const B = require("../../src/server/events/black-friday");

test("coupon, sealed chest and receipts survive abrupt exit before checkpoint, without regrant or reroll", async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "friday-recovery-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const filePath = path.join(dir, "profiles.json");
  const child = spawnSync(process.execPath, ["-e", `
    const { randomUUID } = require('node:crypto');
    const f = require(process.argv[1])({filePath: process.argv[2], journal: true});
    const B = require(process.argv[3]);
    f.store.transact(f.user.token, randomUUID(), 'seed', p => { p.wallet.bucks = 300; });
    const coupon = { productId: 'event:manya-coupon', confirmed: true, eventId: f.run.id, requestId: randomUUID() };
    f.store.confirmMockPurchase(f.user.token, coupon);
    f.act('exchange', 'bucks');
    f.act('chest-ether');
    const boosterInput = f.input('buy', 'rare');
    const boosterReward = B.mutate(f.store, f.user.token, boosterInput, () => 0).reward;
    const chestId = f.p().blackFriday.chests[0].id;
    const prepare = f.input('prepare', chestId);
    B.mutate(f.store, f.user.token, prepare, () => 0);
    process.stdout.write(JSON.stringify({token:f.user.token, coupon, prepare, chestId, boosterInput, boosterReward, now:f.now(), events:f.manager.data, expected:f.p()}));
    process.exit(0);
  `, require.resolve("../helpers/black-friday-fixture"), filePath, require.resolve("../../src/server/events/black-friday")], { encoding: "utf8" });
  assert.equal(child.status, 0, child.stderr);
  const saved = JSON.parse(child.stdout);
  assert.ok(fs.statSync(filePath + ".wal").size > 0);
  const recovered = Object.values(recover(filePath).data.profiles).find(p => p.id === saved.expected.id);
  assert.deepEqual(recovered, saved.expected);
  const store = new ProfileStore({ filePath, journal: true, now: () => saved.now });
  try {
    store.events = new EventManager({ now: () => saved.now });
    store.events.data = saved.events;
    assert.deepEqual(store.find(saved.token).blackFriday, saved.expected.blackFriday);
    assert.equal(store.confirmMockPurchase(saved.token, saved.coupon).replay, true);
    const boosterReplay = B.mutate(store, saved.token, saved.boosterInput, () => { throw Error("redraw"); });
    assert.equal(boosterReplay.replay, true);
    assert.deepEqual(boosterReplay.reward, saved.boosterReward);
    assert.deepEqual(store.find(saved.token).inventory, saved.expected.inventory);
    assert.equal(B.mutate(store, saved.token, saved.prepare, () => { throw Error("reroll"); }).replay, true);
    const before = structuredClone(store.find(saved.token));
    const open = { ...saved.prepare, action: "open", requestId: randomUUID() };
    B.mutate(store, saved.token, open, () => { throw Error("reroll"); });
    const after = store.find(saved.token);
    assert.equal(after.wallet.coins - before.wallet.coins, 250);
    assert.equal(after.wallet.crystals - before.wallet.crystals, 50);
    assert.equal(after.account.vipUntil, saved.now + 3600000);
    assert.equal(after.blackFriday.chests.length, 1);
    assert.equal(after.blackFriday.runs[saved.prepare.runId].tokens, 506);
    assert.equal(after.blackFriday.runs[saved.prepare.runId].tokens - before.blackFriday.runs[saved.prepare.runId].tokens, 6);
    assert.equal(after.blackFriday.runs[saved.prepare.runId].openedChests, 1);
    assert.equal(after.blackFriday.runs[saved.prepare.runId].achievementClaims.friday_case, 1);
    assert.equal(after.greatness - before.greatness, 25);
    assert.equal(B.mutate(store, saved.token, open).replay, true);
    const durable = Object.values(recover(filePath).data.profiles).find(p => p.id === after.id);
    assert.deepEqual(durable.blackFriday, after.blackFriday);
    assert.deepEqual(durable.wallet, after.wallet);
    assert.equal(durable.greatness, after.greatness);
    await store.journal.requestCheckpoint();
    assert.deepEqual(Object.values(recover(filePath).data.profiles).find(p => p.id === after.id), after);
  } finally { await store.close(); }
});
