/* Selected CC0 effects: actual UI actions and native media playback, isolated profiles. */
"use strict";
const assert = require("node:assert/strict"),
  fs = require("node:fs"),
  path = require("node:path"),
  { once } = require("node:events"),
  { randomUUID } = require("node:crypto");
const engines = require("playwright"),
  { createGameServer } = require("../../src/server/game-server"),
  { ProfileStore } = require("../../src/server/profiles/profile-store"),
  { EventManager } = require("../../src/server/events/event-manager"),
  titles = require("../../src/server/progression/title-chest-rewards"),
  lite = require("../../src/server/accounts/lite-account");
const out = path.resolve("../artifacts/selected-audio-greatness-20261028/browser");
fs.mkdirSync(out, { recursive: true });
(async () => {
  const report = [];
  for (const engine of process.argv[2] ? [process.argv[2]] : ["chromium", "firefox", "webkit"]) {
    const now = Math.floor(Date.now() / 60000) * 60000,
      profiles = new ProfileStore({ now: () => now }),
      events = new EventManager({ now: () => now });
    profiles.events = events;
    events.apply("test", "start", { eventId: "easter-hunt", revision: 0, requestId: randomUUID() });
    const auth = profiles.open(),
      p = () => profiles.find(auth.token);
    lite.grantTickets(p(), 100);
    lite.activate(p(), profiles.rouletteConfig, now, events.active().id);
    p().honors.notified = p().honors.claimed;
    const fixture=require('../helpers/browser-established-profile');
    fixture.prepareProfile(profiles,auth);
    const app = createGameServer({
      profiles,
      events,
      autoTick: false,
      testBots: { enabled: false },
      wallNow: () => now,
    });
    let browser;
    try {
      app.httpServer.listen(0, "127.0.0.1");
      await once(app.httpServer, "listening");
      const url = "http://127.0.0.1:" + app.httpServer.address().port;
      browser = await engines[engine].launch({
        headless: true,
        ...(engine === "chromium" ? { channel: "chrome" } : {}),
      });
      const context = await browser.newContext({
        viewport: { width: 1440, height: 1000 },
        reducedMotion: "no-preference",
      });
      await context.addCookies([
        { name: "sferorumiya_session", value: auth.token, url, httpOnly: true },
      ]);
      const page = await context.newPage(),
        errors = [];
      page.on("pageerror", (e) => errors.push(e.message));
      await page.addInitScript(() => {
        // This scenario exercises sounds, not achievement popups generated by
        // its seeded event rewards. Those have separate browser coverage.
        document.addEventListener('killex:profile',e=>{
          localStorage.setItem(KillexPlatform.storageKey('.achievement-notices.v1.')+e.detail.id,
            JSON.stringify(Object.fromEntries((e.detail.progress?.achievements || []).map(a=>[
              a.eventRunId?a.id+':'+a.eventRunId:a.id,10]))));
        });
        window.audioAttempts = [];
        window.audioPlaying = [];
        window.audioElements = [];
        const Native = window.Audio;
        window.Audio = function (...args) {
          const a = new Native(...args);
          if (!args[0]?.endsWith(".wav")) return a;
          window.audioElements.push(a);
          const play = a.play.bind(a);
          a.play = () => {
            const row = { file: a.src.split("/").pop(), muted: a.muted, at: performance.now() };
            window.audioAttempts.push(row);
            return play().then(
              () => (row.ok = true),
              (e) => {
                row.error = e.name;
                throw e;
              },
            );
          };
          a.addEventListener("playing", () => {
            if (!a.muted)
              window.audioPlaying.push({ file: a.src.split("/").pop(), at: performance.now() });
          });
          return a;
        };
      });
      await fixture.prepareContext(context);
      await page.goto(url);
      await page.waitForFunction(() => !document.getElementById("playButton").disabled);
      await fixture.clearInitialDialogs(page);
      await page.bringToFront();
      // Prime native media through an ordinary silent user gesture first.
      // Slow first decoding is intentionally suppressed by the stale-sound
      // guard and is not a failure of the selected effect itself.
      await page.locator('#settingsButton').click();
      await page.waitForFunction(()=>audioElements.length>0 && audioElements.every(a=>a.readyState>=2));
      await page.locator('#settingsButton').click();
      const close = async () => {
        await page.evaluate(() =>
          document.querySelectorAll("dialog[open]").forEach((d) => d.close()),
        );
      };
      await close();
      const heard = async (id) =>
        page.evaluate(
          (id) =>
            audioAttempts.filter((a) => !a.muted && a.file === id + "-selected-v1.wav").length,
          id,
        );
      for (const [button, sound, dialog] of [
        ["questsSection", "quests", "questsDialog"],
        ["shopSection", "shop", "boosterDialog"],
        ["wardrobeSection", "wardrobe", "skinsDialog"],
        ["clanSection", "clan", null],
      ]) {
        await page.locator("#" + button).click();
        if (dialog) await page.locator("#" + dialog + "[open]").waitFor();
        else await page.waitForFunction(() => document.querySelector("dialog[open]"));
        await page.waitForFunction(
          (sound) => audioPlaying.some((a) => a.file === sound + "-selected-v1.wav"),
          sound,
        );
        await page.waitForFunction(
          (sound) =>
            audioElements.some(
              (a) => a.src.endsWith(sound + "-selected-v1.wav") && a.currentTime > 0.04,
            ),
          sound,
        );
        assert.equal(await heard(sound), 1, button);
        console.log(engine + " native " + sound);
        await close();
      }
      // No invented effect for the unselected Inventory action.
      const count = await page.evaluate(() => audioAttempts.filter((a) => !a.muted).length);
      await page.locator("#inventorySection").click();
      await page.locator("#boosterDialog[open]").waitFor();
      assert.equal(await page.evaluate(() => audioAttempts.filter((a) => !a.muted).length), count);
      await close();
      await page.locator("#settingsButton").click();
      await page.locator("#soundVolume").press("Home");
      await page.locator("#settingsButton").click();
      assert.ok(await page.evaluate(() => audioElements.every((a) => a.paused)));
      await page.locator("#questsSection").click();
      await page.locator("#questsDialog[open]").waitFor();
      assert.equal(await heard("quests"), 1);
      await close();
      await page.locator("#settingsButton").click();
      await page.locator("#soundVolume").press("End");
      await page.locator("#settingsButton").click();
      await page.locator("#questsSection").click();
      await page.waitForFunction(
        () =>
          audioAttempts.filter((a) => !a.muted && a.file === "quests-selected-v1.wav").length === 2,
      );
      await close();
      // New rank is acknowledged once by the real endpoint; another profile load stays silent.
      p().greatness = 100;
      titles.awardTitles(p(), now);
      p().revision++;
      const refresh = () =>
        page.evaluate(async () => {
          const r = await fetch("/api/profile"),
            v = await r.json();
          document.dispatchEvent(new CustomEvent("killex:profile", { detail: v.profile }));
        });
      await refresh();
      await page.locator("#titleEarnedDialog[open]").waitFor();
      await page.waitForFunction(() =>
        audioPlaying.some((a) => a.file === "title-selected-v1.wav"),
      );
      await page
        .locator("#titleEarnedDialog")
        .getByRole("button", { name: "Отлично", exact: true })
        .click();
      await refresh();
      assert.equal(await heard("title"), 1);
      await close();
      await page.locator("#rouletteButton").click();
      const spin = page.locator(".roulette-spin:not(.roulette-spin-five)");
      await spin.waitFor();
      await page.evaluate(() => {
        window.tickProbe = [];
        const follow = KillexAudio.followRoulette;
        KillexAudio.followRoulette = (...args) => {
          const play = args[3];
          args[3] = (id) => {
            tickProbe.push({
              at: performance.now(),
              time: args[0].currentTime,
              progress: args[0].effect.getComputedTiming().progress,
            });
            play(id);
          };
          return follow(...args);
        };
      });
      await spin.click();
      await page.waitForFunction(() =>
        document.querySelector(".roulette-status").textContent.startsWith("Поздравляем!"),
      );
      const ticks = await heard("roulette-tick");
      assert.ok(ticks >= 5, engine + " roulette clicks: " + ticks);
      const played = await page.evaluate(() =>
        audioPlaying.filter((a) => a.file === "roulette-tick-selected-v1.wav").map((a) => a.at),
      );
      assert.ok(played.length >= 5);
      const probe = await page.evaluate(() => tickProbe);
      const attempts = await page.evaluate(() =>
        audioAttempts.filter((a) => !a.muted && a.file === "roulette-tick-selected-v1.wav"),
      );
      // Firefox may emit 'playing' twice around one seek, and headless rendering
      // skips frames. Compare actual play calls with the animation, not event gaps.
      assert.ok(attempts.every((a) => probe.some((p) => Math.abs(a.at - p.at) < 20)));
      const speed = (a, b) => (b.progress - a.progress) / (b.time - a.time);
      assert.ok(speed(probe.at(-3), probe.at(-1)) < speed(probe[0], probe[2]));
      // Native fast playback, five-ticket batches, gain/rate parity and voice
      // cleanup are exercised by roulette-volume.test.cjs in all three engines.
      await spin.click();
      await page.waitForFunction(
        () =>
          document.querySelector(".roulette-wheel-frame.is-spinning") ||
          document.querySelector(".is-spinning"),
      );
      await page.locator("#rouletteDialog .booster-close").click();
      await page.waitForFunction(() => !document.querySelector("#rouletteDialog .is-spinning"));
      const stopped = await heard("roulette-tick");
      await page.waitForTimeout(200);
      assert.equal(await heard("roulette-tick"), stopped);
      await page.waitForFunction(() => audioElements.every((a) => a.readyState >= 2));
      const failures = await page.evaluate(() => audioAttempts.filter((a) => !a.muted && a.error));
      assert.deepEqual(failures, []);
      assert.deepEqual(errors, []);
      report.push({
        engine,
        ui: true,
        nativePlayback: true,
        mute: true,
        titleOnce: true,
        rouletteTicks: ticks,
        closedStops: true,
        errors,
      });
      console.log(engine + ": selected UI audio, title, mute and roulette passed");
    } catch (error) {
      if (browser) {
        const pages = browser.contexts()[0]?.pages();
        if (pages?.[0])
          console.log(
            JSON.stringify(
              await pages[0].evaluate(() => ({
                attempts: audioAttempts.filter((a) => !a.muted),
                audio: audioElements
                  .filter((a) => a.src.includes("selected"))
                  .map((a) => ({
                    file: a.src.split("/").pop(),
                    time: a.currentTime,
                    paused: a.paused,
                    ready: a.readyState,
                  })),
              })),
            ),
          );
      }
      throw error;
    } finally {
      if (browser) await browser.close();
      await app.close();
    }
  }
  fs.writeFileSync(path.join(out, "selected-audio.json"), JSON.stringify(report, null, 2));
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
